import { format } from 'prettier';
import { describe, expect, it } from 'vitest';
import type { NewEvent, SpecrunEvent } from '../events/eventSchema.js';
import { deriveState } from '../events/taskState.js';
import type { Spec } from '../spec/specSchema.js';
import { formatDuration, renderProgress } from './renderProgress.js';

const spec: Spec = {
  title: 'Demo spec',
  tasks: [
    { id: 'D-1', title: 'Schemas', phase: 1, needs: [], model: 'default', size: 'S' },
    { id: 'D-2', title: 'Event log', phase: 1, needs: ['D-1'], model: 'strong', size: 'M' },
    { id: 'D-3', title: 'Runner', phase: 2, needs: ['D-2'], model: 'strong', size: 'L' },
    { id: 'D-4', title: 'Dashboard', phase: 2, needs: ['D-1'], model: 'default', size: 'M' },
  ],
};

function log(...events: NewEvent[]): SpecrunEvent[] {
  return events.map(
    (event) => ({ ...event, v: 1, at: '2026-11-09T10:00:00.000Z', runId: 'r' }) as SpecrunEvent,
  );
}

function session(task: string, sessionId: string, turns: number, costUsd: number): NewEvent[] {
  return [
    {
      t: 'session.started',
      task,
      sessionId: null,
      segment: 0,
      attempt: 1,
      model: 'opus',
      reason: 'start',
      prompt: { protocol: 1, spec: 1, brief: 1, deps: 0 },
    },
    {
      t: 'session.finished',
      task,
      sessionId,
      segment: 0,
      outcome: 'completed',
      turns,
      peakContext: 57_600,
      inputTokens: 10,
      outputTokens: 4_000,
      cacheRead: 300_000,
      cacheWrite: 30_000,
      costUsd,
      durationMs: 9 * 60_000,
    },
  ];
}

function mixedStates(): SpecrunEvent[] {
  return log(
    ...session('D-1', 's1', 15, 0.384),
    {
      t: 'task.completed',
      task: 'D-1',
      sessionId: 's1',
      payload: {
        summary: 'Schemas | loaders',
        commitMessage: 'feat(config): schemas',
        notes: ['note'],
        deviations: [
          { kind: 'ambiguity', decision: 'SRD-3', what: 'Kept the alias', why: 'simplest' },
          { kind: 'test-trap', what: 'Temp dir\nleaked', why: 'missing afterEach' },
        ],
      },
    },
    {
      t: 'task.committed',
      task: 'D-1',
      commit: '0123456789abcdef',
      filesChanged: 4,
      insertions: 120,
      deletions: 3,
    },
    ...session('D-2', 's2', 40, 2.5),
    { t: 'task.blocked', task: 'D-2', reason: 'verify red after 2 rounds', source: 'verify' },
    {
      t: 'budget.exceeded',
      task: 'D-2',
      size: 'M',
      turns: 40,
      costUsd: 2.5,
      limit: { turns: 30, usd: 2 },
    },
    session('D-4', 's4', 3, 0.1)[0] as NewEvent,
  );
}

describe('renderProgress', () => {
  it('renders a spec in mixed states', () => {
    expect(renderProgress(spec, deriveState(spec, mixedStates()))).toMatchInlineSnapshot(`
      "<!-- Generated by specrun from events.jsonl — do not edit. -->

      # Demo spec — Progress

      | Phase | Task | Title     | Size | Model   | Status                | Sessions | Turns | Peak ctx | Cost  | Commit  | Summary                   |
      | ----- | ---- | --------- | ---- | ------- | --------------------- | -------- | ----- | -------- | ----- | ------- | ------------------------- |
      | 1     | D-1  | Schemas   | S    | default | done                  | 1        | 15    | 58k      | $0.38 | 0123456 | Schemas \\| loaders        |
      | 1     | D-2  | Event log | M    | strong  | blocked (over budget) | 1        | 40    | 58k      | $2.50 | —       | verify red after 2 rounds |
      | 2     | D-3  | Runner    | L    | strong  | todo                  | —        | —     | —        | —     | —       |                           |
      | 2     | D-4  | Dashboard | M    | default | interrupted           | —        | —     | —        | —     | —       |                           |

      ## Deviations

      - **D-1** [ambiguity] SRD-3: Kept the alias — simplest
      - **D-1** [test-trap] Temp dir leaked — missing afterEach

      ## Totals

      - Tasks: 4 (1 done · 1 blocked · 1 interrupted · 1 todo)
      - Sessions: 2 · Turns: 55 · Cost: $2.88 · Time: 18m
      "
    `);
  });

  it('is already Prettier-formatted, so committing it keeps format:check green', async () => {
    const markdown = renderProgress(spec, deriveState(spec, mixedStates()));
    expect(await format(markdown, { parser: 'markdown', printWidth: 100 })).toBe(markdown);
  });

  it('formats durations like the run stats', () => {
    expect(formatDuration(9 * 60_000)).toBe('9m');
    expect(formatDuration(65 * 60_000)).toBe('1h 05m');
  });
});
