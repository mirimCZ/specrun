import type { TaskState, SpecState, TaskStatus } from '../events/taskState.js';
import { formatQuestion } from '../events/formatQuestion.js';
import type { Spec } from '../spec/specSchema.js';
import { topologicalOrder } from '../spec/taskOrder.js';

export const PROGRESS_FILE = 'PROGRESS.md';
export const GENERATED_MARKER = '<!-- Generated by specrun from events.jsonl — do not edit. -->';

const NONE = '—';
const STATUSES: readonly TaskStatus[] = ['done', 'blocked', 'interrupted', 'todo'];

/** Deterministic: depends only on spec and state, and is already Prettier-formatted. */
export function renderProgress(spec: Spec, state: SpecState): string {
  const order = topologicalOrder(spec);
  const rows = order.map((task) => {
    const s = state.tasks.get(task.id);
    const ran = s !== undefined && s.totals.sessions > 0;
    return [
      String(task.phase),
      task.id,
      task.title,
      task.size,
      task.model,
      s === undefined ? 'todo' : statusLabel(s),
      ran ? String(s.totals.sessions) : NONE,
      ran ? String(s.totals.turns) : NONE,
      ran ? formatTokens(s.totals.peakContext) : NONE,
      ran ? formatUsd(s.totals.costUsd) : NONE,
      s?.commit == null ? NONE : s.commit.slice(0, 7),
      s?.lastCompleted?.summary ?? (s?.status === 'blocked' ? (s.blockedReason ?? '') : ''),
    ];
  });

  const deviations = order.flatMap((task) =>
    (state.tasks.get(task.id)?.lastCompleted?.deviations ?? []).map((d) => {
      const decision = d.decision === undefined ? '' : `${inline(d.decision)}: `;
      const line = `- **${task.id}** [${d.kind}] ${decision}${inline(d.what)} — ${inline(d.why)}`;
      return d.question === undefined ? line : `${line}\n  - ${formatQuestion(d.question)}`;
    }),
  );

  const counts = STATUSES.map((status) => {
    const n = order.filter((task) => (state.tasks.get(task.id)?.status ?? 'todo') === status);
    return `${n.length} ${status}`;
  });
  const totals = [...state.tasks.values()].reduce(
    (sum, s) => ({
      sessions: sum.sessions + s.totals.sessions,
      turns: sum.turns + s.totals.turns,
      costUsd: sum.costUsd + s.totals.costUsd,
      durationMs: sum.durationMs + s.totals.durationMs,
    }),
    { sessions: 0, turns: 0, costUsd: 0, durationMs: 0 },
  );

  return [
    GENERATED_MARKER,
    '',
    `# ${inline(spec.title)} — Progress`,
    '',
    table(
      [
        'Phase',
        'Task',
        'Title',
        'Size',
        'Model',
        'Status',
        'Sessions',
        'Turns',
        'Peak ctx',
        'Cost',
        'Commit',
        'Summary',
      ],
      rows,
    ),
    '',
    '## Deviations',
    '',
    ...(deviations.length === 0 ? ['None.'] : deviations),
    '',
    '## Totals',
    '',
    `- Tasks: ${order.length} (${counts.join(' · ')})`,
    `- Sessions: ${totals.sessions} · Turns: ${totals.turns} · Cost: ${formatUsd(totals.costUsd)} · Time: ${formatDuration(totals.durationMs)}`,
    '',
  ].join('\n');
}

function statusLabel(s: TaskState): string {
  return s.budgetExceeded ? `${s.status} (over budget)` : s.status;
}

/** Same rounding as the bootstrap runner's stats: `58k`. */
export function formatTokens(n: number): string {
  return `${Math.round(n / 1000)}k`;
}

export function formatUsd(n: number): string {
  return `$${n.toFixed(2)}`;
}

export function formatDuration(ms: number): string {
  const minutes = Math.round(ms / 60_000);
  if (minutes < 60) return `${minutes}m`;
  return `${Math.floor(minutes / 60)}h ${String(minutes % 60).padStart(2, '0')}m`;
}

/** Agent-written text on one line, safe inside a table cell. */
function inline(text: string): string {
  return text.replace(/\s*\n\s*/g, ' ').trim();
}

// Padded like Prettier formats markdown tables, so `format:check` stays green on the file.
function table(header: string[], rows: string[][]): string {
  const cell = (text: string): string => inline(text).replace(/\|/g, '\\|');
  const all = [header, ...rows].map((row) => row.map(cell));
  const widths = header.map((_, i) => Math.max(3, ...all.map((row) => (row[i] ?? '').length)));
  const line = (row: string[]): string =>
    `| ${widths.map((w, i) => (row[i] ?? '').padEnd(w)).join(' | ')} |`;
  const [head = [], ...body] = all;
  return [line(head), line(widths.map((w) => '-'.repeat(w))), ...body.map(line)].join('\n');
}
